const STRINGS = Object.freeze({ en: EN, tr: TR });

/**
 * Looks up a text and fills its {placeholders}. Unknown placeholders stay as they are, and an
 * unknown key comes back unchanged so a missing text is easy to spot (the tests check for that).
 * @param {string} lang "en" or "tr" (anything else falls back to English)
 * @param {string} key
 * @param {Record<string, string|number>} [params] `n` also picks the singular or plural form
 * @returns {string}
 */
export function translate(lang, key, params = {}) {
  const table = Object.hasOwn(STRINGS, lang) ? STRINGS[lang] : STRINGS.en;
  if (!Object.hasOwn(table, key)) return key;
  const entry = table[key];
  const template = typeof entry === 'string' ? entry : params.n === 1 ? entry.one : entry.other;
  return template.replace(/\{(\w+)\}/g, (match, name) => (Object.hasOwn(params, name) ? String(params[name]) : match));
}
